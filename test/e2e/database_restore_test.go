// TestPostgresDumpRestore proves logical recovery of synthetic rows, constraints,
// and a sequence, rather than merely checking that a dump file is readable.
// It uses one local target: multi-target hook execution and SFTP transport are
// separate concerns. It does not test live PGDATA backup, PITR, or concurrent
// database writes. Run only while holding the dedicated daemon reservation:
//
//	SABON_E2E_ISOLATED=1 DOCKER_HOST=unix:///path/to/isolated/docker.sock \
//	TMPDIR=/path/shared-with-daemon go test -tags e2e ./test/e2e -run '^TestPostgresDumpRestore$' -v -count=1 -timeout=15m
func TestPostgresDumpRestore(t *testing.T) {
	if os.Getenv("SABON_E2E_ISOLATED") != "1" {
		t.Skip("requires SABON_E2E_ISOLATED=1")
	}
	host := os.Getenv("DOCKER_HOST")
	if host == "" || host == "unix:///var/run/docker.sock" || host == "unix:///run/docker.sock" {
		t.Fatal("set DOCKER_HOST explicitly to an isolated daemon")
	}
	t.Setenv("DOCKER_CONTEXT", "")
	mustRun(t, nil, "docker", "version")
	const postgresImage = "postgres:17.6-bookworm"
	id := fmt.Sprintf("sabon-pg-accept-%d", time.Now().UnixNano())
	source, destination := id+"-source", id+"-destination"
	dumps, sourceData, destinationData := id+"-dumps", id+"-source-data", id+"-destination-data"
	cache, image := id+"-cache", "sabon-mover:"+id
	work, err := os.MkdirTemp("", id)
	if err != nil {
		t.Fatal(err)
	}
	// Track only resources created by this fixture; cleanup also runs after a
	// setup failure. No global prune, shared cache, or default daemon is used.
	var containers, volumes []string
	imageBuilt := false
	t.Cleanup(func() {
		cleanup := func(args ...string) {
			if out, err := run(t, "docker", args...); err != nil {
				t.Errorf("cleanup docker %v: %v\n%s", args, err, out)
			}
		}
		for _, container := range containers {
			cleanup("rm", "-f", container)
		}
		out, err := run(t, "docker", "ps", "-aq", "--filter", "label=acceptance.fixture="+id)
		if err != nil {
			t.Errorf("list fixture movers: %v\n%s", err, out)
		} else if ids := strings.Fields(out); len(ids) > 0 {
			cleanup(append([]string{"rm", "-f"}, ids...)...)
		}
		for _, volume := range volumes {
			cleanup("volume", "rm", volume)
		}
		// Restic restore/repository files are created as root by movers.
		cleanup("run", "--rm", "--network", "none", "-v", work+":/w", "alpine:3", "sh", "-c", "rm -rf /w/*")
		if err := os.RemoveAll(work); err != nil {
			t.Error(err)
		}
		if imageBuilt {
			cleanup("image", "rm", image)
		}
	})
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	mustRun(t, nil, "docker", "build", "-f", filepath.Join(root, "Dockerfile.mover"), "-t", image,
		"--build-arg", "VERSION=e2e", root)
	imageBuilt = true
	bin := filepath.Join(t.TempDir(), "sabon")
	mustRun(t, nil, "go", "build", "-o", bin, filepath.Join(root, "cmd", "sabon"))
	for _, volume := range []string{dumps, sourceData, destinationData, cache} {
		mustRun(t, nil, "docker", "volume", "create", volume)
		volumes = append(volumes, volume)
	}
	repo, restored := filepath.Join(work, "repo"), filepath.Join(work, "restored")
	if err := os.MkdirAll(repo, 0o777); err != nil {
		t.Fatal(err)
	}
	config := filepath.Join(work, "targets.yaml")
	if err := os.WriteFile(config, []byte("targets:\n  - name: local\n    path: "+repo+"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	env := []string{
		"SABON_CONFIG=" + config, "SABON_MOVER_IMAGE=" + image, "RESTIC_PASSWORD=" + password,
		"SABON_RUNTIME=standalone", "SABON_INSTANCE=" + id, "SABON_CACHE_VOLUME=" + cache,
		"SABON_MOVER_HISTORY=0", "SABON_BACKUP_TIMEOUT=2m", "SABON_SNAPSHOT=none",
		"SABON_MOVER_LABELS=acceptance.fixture=" + id,
	}
	// Only the logical dump is a backup source; the live PGDATA volume must
	// never be used to recover the destination database.
	spec := fmt.Sprintf(`repo: %s
auto: false
extraVolumes: [%s]
preHooks:
  - timeout: 60s
    command: [sh, -ec, 'pg_dump -U postgres -d synthetic --format=custom --file=/dumps/synthetic.dump']
`, id, dumps)
	mustRun(t, nil, "docker", "run", "-d", "--name", source, "--network", "none",
		"--label", "sabon.enable=true", "--label", "sabon.instance="+id, "--label", "sabon.backup="+spec,
		"-e", "POSTGRES_PASSWORD=synthetic-only", "-e", "POSTGRES_DB=synthetic",
		"-v", sourceData+":/var/lib/postgresql/data", "-v", dumps+":/dumps", postgresImage)
	containers = append(containers, source)
	waitAcceptancePostgres(t, source, "synthetic")
	psql := func(container, database, sql string) string {
		t.Helper()
		return strings.TrimSpace(mustRun(t, nil, "docker", "exec", container,
			"psql", "-X", "-U", "postgres", "-d", database, "-v", "ON_ERROR_STOP=1", "-At", "-c", sql))
	}
	psql(source, "synthetic", `
CREATE TABLE accounts (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE);
CREATE TABLE entries (id integer PRIMARY KEY, account_id integer NOT NULL REFERENCES accounts(id), amount numeric(10,2) NOT NULL);
INSERT INTO accounts(name) VALUES ('alpha'), ('café');
INSERT INTO entries VALUES (11, 1, 12.50), (12, 1, -2.25), (13, 2, 99.00);
`)
	const query = `SELECT a.id, a.name, count(e.id), sum(e.amount) FROM accounts a JOIN entries e ON e.account_id = a.id GROUP BY a.id, a.name ORDER BY a.id`
	const want = "1|alpha|2|10.25\n2|café|1|99.00"
	if got := psql(source, "synthetic", query); got != want {
		t.Fatalf("synthetic seed mismatch: got %q, want %q", got, want)
	}
	mustRun(t, nil, "docker", "exec", source, "test", "!", "-e", "/dumps/synthetic.dump")
	mustRun(t, env, bin, "backup", "--app", id, "--target", "local")
	mustRun(t, nil, "docker", "exec", source, "test", "-s", "/dumps/synthetic.dump")
	// Destroy the original dump and stop its database before restoring. The
	// import below can only consume bytes recovered from the backup repository.
	mustRun(t, nil, "docker", "exec", source, "rm", "/dumps/synthetic.dump")
	mustRun(t, nil, "docker", "stop", source)
	mustRun(t, env, bin, "restore", "--app", id, "--target", "local", "--into", restored)
	dump := filepath.Join(restored, "data", dumps, "synthetic.dump")
	if info, err := os.Stat(dump); err != nil || info.Size() == 0 {
		t.Fatalf("restored dump missing/empty: %v", err)
	}
	mustRun(t, nil, "docker", "run", "-d", "--name", destination, "--network", "none",
		"-e", "POSTGRES_PASSWORD=synthetic-only", "-e", "POSTGRES_DB=recovered",
		"-v", destinationData+":/var/lib/postgresql/data", "-v", restored+":/restore:ro", postgresImage)
	containers = append(containers, destination)
	waitAcceptancePostgres(t, destination, "recovered")
	if got := psql(destination, "recovered", "SELECT count(*) FROM information_schema.tables WHERE table_schema = 'public'"); got != "0" {
		t.Fatalf("destination must start empty, got %q public tables", got)
	}
	mustRun(t, nil, "docker", "exec", destination, "pg_restore", "-U", "postgres", "-d", "recovered",
		"--exit-on-error", "--no-owner", "/restore/data/"+dumps+"/synthetic.dump")
	if got := psql(destination, "recovered", query); got != want {
		t.Fatalf("recovered rows mismatch: got %q, want %q", got, want)
	}
	if got := psql(destination, "recovered", `WITH inserted AS (INSERT INTO accounts(name) VALUES ('after-restore') RETURNING id) SELECT id FROM inserted`); got != "3" {
		t.Fatalf("restored identity sequence did not continue at 3: %q", got)
	}
	if out, err := run(t, "docker", "exec", destination, "psql", "-X", "-U", "postgres", "-d", "recovered",
		"-v", "ON_ERROR_STOP=1", "-c", "INSERT INTO entries VALUES (99, 999, 1.00)"); err == nil || !strings.Contains(out, "foreign key constraint") {
		t.Fatalf("restored foreign key should reject an orphan row: %v\n%s", err, out)
	}
	t.Log("pg_dump prehook -> named-volume backup -> restored dump -> fresh PostgreSQL import: exact synthetic rows, identity sequence, and foreign key verified")
}

func waitAcceptancePostgres(t *testing.T, container, database string) {
	t.Helper()
	deadline := time.Now().Add(90 * time.Second)
	var out string
	for {
		// TCP avoids mistaking the entrypoint's temporary Unix-socket-only
		// initialization server for the final server.
		var err error
		out, err = run(t, "docker", "exec", "-e", "PGPASSWORD=synthetic-only", container,
			"psql", "-X", "-h", "127.0.0.1", "-U", "postgres", "-d", database, "-At", "-c", "SELECT 1")
		if err == nil && strings.TrimSpace(out) == "1" {
			return
		}
		if time.Now().After(deadline) {
			logs, _ := run(t, "docker", "logs", container)
			t.Fatalf("PostgreSQL did not become ready: %s\n%s", out, logs)
		}
		time.Sleep(time.Second)
	}
}
